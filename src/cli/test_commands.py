def _fixup_node_identity(cfg_dir: Path, data_dir: Path, role: str, node_id: int,
                         network_mgr, print_info, svc_name: str) -> None:
    """Fix identity and role for a node provisioned from genesis donor.

    Genesis copy gives every node the same CA private keys and the donor's
    role (usually root).  We must:
      1. Wipe the entire CA directory so that cellframe-node generates its
         own unique node-addr.dcert on first start.  The root public certs
         needed for chain validation are baked into the Docker image.
      2. Patch node-role in the network config to match the requested role.
      3. Remove DAG-PoA signing cert reference for non-root nodes.
    """
    import re as _re
    import shutil as _shutil

    ca_dir = data_dir / "lib" / "ca"
    if ca_dir.exists():
        for f in ca_dir.iterdir():
            if f.name == "node-addr.dcert" or ".pvt." in f.name:
                f.unlink()
        print_info(_("    [{}] removed donor private keys from var/lib/ca").format(svc_name))

    net_name = network_mgr.topology.network.name
    net_cfg = cfg_dir / "network" / f"{net_name}.cfg"
    if net_cfg.exists():
        content = net_cfg.read_text()
        content = _re.sub(r'(?m)^node-role\s*=\s*\S+', f'node-role={role}', content)
        if role not in ("root",):
            content = _re.sub(r'(?m)^events-sign-cert\s*=.*$', '#events-sign-cert=', content)
        net_cfg.write_text(content)
        print_info(_("    [{}] patched network config: role={}").format(svc_name, role))


def _provision_docker_compose(compose_mgr, docker_compose, print_info, print_success, print_warning, print_error):
    """Add docker-compose services to compose file, start them, install packages.

    Services generated by ``docker_compose_gen`` may carry a ``_gen_packages``
    key — those packages are installed on the containers themselves using the
    prototype pattern (install once, commit, clone to siblings).

    Returns:
        Clean service dict (without ``_gen_packages`` markers).
    """
    dc_packages: dict[str, list[str]] = {}
    clean_services: dict = {}
    for svc_name, svc_def in docker_compose.items():
        svc_copy = dict(svc_def) if isinstance(svc_def, dict) else svc_def
        gen_pkg = svc_copy.pop("_gen_packages", None)
        if gen_pkg:
            dc_packages[svc_name] = gen_pkg.split()
        clean_services[svc_name] = svc_copy

    compose_mgr.add_docker_compose_services(clean_services)
    svc_names = list(clean_services.keys())
    if not svc_names:
        return clean_services

    pkg_groups: dict[tuple, list[str]] = {}
    for svc, pkgs in dc_packages.items():
        key = tuple(sorted(pkgs))
        pkg_groups.setdefault(key, []).append(svc)

    clone_map: dict[str, list[str]] = {}
    deferred_svcs: set[str] = set()
    for _pkg_key, group_svcs in pkg_groups.items():
        if len(group_svcs) > 1:
            prototype = group_svcs[0]
            clone_map[prototype] = group_svcs[1:]
            deferred_svcs.update(group_svcs[1:])

    start_first = [s for s in svc_names if s not in deferred_svcs]
    try:
        compose_mgr.up(services=start_first, detach=True, wait=False, no_build=True)
        print_success(_("  Started: {}").format(', '.join(start_first)))
    except Exception as e:
        print_error(_("  Failed to start docker_compose services: {}").format(e))
        return clean_services

    for svc, pkgs in dc_packages.items():
        if svc in deferred_svcs:
            continue
        pkg_str = " ".join(pkgs)
        try:
            exit_code, output = compose_mgr.exec(
                svc, ["bash", "-c",
                      f"apt-get update -qq && apt-get install -y -qq {pkg_str} "
                      f"&& rm -rf /var/lib/apt/lists/*"]
            )
            if exit_code != 0:
                print_warning(_("  [{}] package install failed: {}").format(svc, output[:200]))
            else:
                print_info(_("  [{}] installed: {}").format(svc, pkg_str))
        except Exception as e:
            print_warning(_("  [{}] package install error: {}").format(svc, e))

    if clone_map:
        _commit_and_clone_prototypes(compose_mgr, clone_map, print_info, print_warning)
        try:
            compose_mgr.up(
                services=list(deferred_svcs), detach=True,
                wait=False, no_build=True,
            )
            print_success(_("  Started from prototype: {}").format(', '.join(sorted(deferred_svcs))))
        except Exception as e:
            print_error(_("  Failed to start cloned docker_compose services: {}").format(e))

    return clean_services


def _commit_and_clone_prototypes(compose_mgr, clone_map, print_info, print_warning):
    """Docker-commit prototype containers and replicate images to siblings.

    For each prototype service, commit its writable layer (installed packages
    etc.) and then point all sibling services to the committed image so they
    start pre-configured without running apt-get again.
    """
    try:
        containers = compose_mgr.ps()
    except Exception as e:
        print_warning(_("  prototype commit: cannot list containers: {}").format(e))
        return

    svc_to_container = {}
    for c in containers:
        svc = c.labels.get("com.docker.compose.service")
        if svc:
            svc_to_container[svc] = c

    image_map: dict[str, str] = {}

    for prototype, siblings in clone_map.items():
        container = svc_to_container.get(prototype)
        if not container:
            print_warning(_("  prototype commit: container for '{}' not found").format(prototype))
            continue

        container.reload()
        tag = f"prototype-{prototype}"
        try:
            container.commit(repository=tag)
        except Exception as e:
            print_warning(_("  prototype commit failed for '{}': {}").format(prototype, e))
            continue

        image_map[prototype] = tag
        for svc in siblings:
            image_map[svc] = tag
        print_info(_("  [{}] committed → cloned to {} sibling(s)").format(prototype, len(siblings)))

    if image_map:
        compose_mgr.set_service_images(image_map)


def _provision_node_compose(network_mgr, node_compose, base_path, config_loader, print_info, print_success, print_warning, print_error, suite_variables=None):
    """
    Provision additional cellframe nodes declared in suite.node_compose.

    New nodes are registered in ``network_mgr.nodes`` (the single source of
    truth) and receive IDs that follow the existing base-topology nodes.

    Args:
        node_compose: Dict[str, NodeComposeSpec] — keys are service names
    """
    import ipaddress
    import re
    import shutil
    _asan_ignore = shutil.ignore_patterns("asan.*")

    from ..network.models import NodeConfig

    settings = network_mgr.topology.network_settings
    base_ip = ipaddress.ip_address(settings.base_ip)

    cache_dir = Path(config_loader.get_paths_config().get('cache_dir', '../../cache'))
    if not cache_dir.is_absolute():
        cache_dir = (base_path / cache_dir).resolve()

    max_existing_id = max(
        (cfg.node_id for cfg in network_mgr.nodes.values()), default=0
    )
    next_auto_id = max_existing_id + 1

    compose_specs: list[dict] = []
    packages_to_install: dict[str, list[str]] = {}

    for svc_name, spec in node_compose.items():
        node_id = spec.id if spec.id is not None else next_auto_id
        next_auto_id = max(next_auto_id, node_id) + 1

        ip_addr = str(base_ip + node_id - 1)
        http_port = settings.base_http_port + (node_id - 1)

        node_cfg = NodeConfig(
            node_id=node_id,
            role=spec.role,
            node_type=spec.role,
            rpc_port=settings.base_rpc_port + (node_id - 1),
            p2p_port=settings.base_p2p_port + (node_id - 1),
            cf_port=settings.base_cf_port + (node_id - 1),
            http_port=http_port,
            ip_address=ip_addr,
        )
        network_mgr.nodes[svc_name] = node_cfg

        node_spec_dict = {
            'id': node_id,
            'service_name': svc_name,
            'role': spec.role,
            'ip_address': ip_addr,
            'http_port': http_port,
        }
        if spec.cap_add:
            node_spec_dict['cap_add'] = list(spec.cap_add)
        compose_specs.append(node_spec_dict)

        cfg_dir = cache_dir / "configs" / f"node{node_id}"
        data_dir = cache_dir / "data" / f"node{node_id}"
        source = spec.source.strip().lower()
        freshly_cloned = False

        if source == "genesis":
            src_node = _find_donor_node(cache_dir, "configs")
            if src_node:
                if cfg_dir.exists():
                    shutil.rmtree(cfg_dir, ignore_errors=True)
                shutil.copytree(cache_dir / "configs" / src_node, cfg_dir, dirs_exist_ok=True, ignore=_asan_ignore)
                print_info(_("    configs from genesis ({})").format(src_node))
            if src_node and not data_dir.exists():
                src_data = cache_dir / "data" / src_node
                if src_data.exists():
                    shutil.copytree(src_data, data_dir, dirs_exist_ok=True, ignore=_asan_ignore)
                    freshly_cloned = True
            _fixup_node_identity(cfg_dir, data_dir, spec.role, node_id,
                                 network_mgr, print_info, svc_name)
        elif source.startswith("node-"):
            clone_m = re.match(r'node-(\d+)', source)
            if not clone_m:
                print_warning(_("  [{}] bad source '{}'").format(svc_name, source))
                continue
            clone_id = clone_m.group(1)
            src_cfg = cache_dir / "configs" / f"node{clone_id}"
            src_data = cache_dir / "data" / f"node{clone_id}"
            if src_cfg.exists():
                if cfg_dir.exists():
                    shutil.rmtree(cfg_dir, ignore_errors=True)
                shutil.copytree(src_cfg, cfg_dir, dirs_exist_ok=True, ignore=_asan_ignore)
            if src_data.exists() and not data_dir.exists():
                shutil.copytree(src_data, data_dir, dirs_exist_ok=True, ignore=_asan_ignore)
                freshly_cloned = True
            _fixup_node_identity(cfg_dir, data_dir, spec.role, node_id,
                                 network_mgr, print_info, svc_name)
        elif source == "fresh":
            cfg_dir.mkdir(parents=True, exist_ok=True)
            (cfg_dir / "cellframe-node.cfg.d").mkdir(exist_ok=True)
            (cfg_dir / "network").mkdir(exist_ok=True)
            data_dir.mkdir(parents=True, exist_ok=True)
            donor = _find_donor_node(cache_dir, "configs")
            if donor and not (cfg_dir / "cellframe-node.cfg").exists():
                shutil.copy2(cache_dir / "configs" / donor / "cellframe-node.cfg", cfg_dir / "cellframe-node.cfg")
        else:
            print_warning(_("  [{}] unknown source '{}', using fresh").format(svc_name, source))
            cfg_dir.mkdir(parents=True, exist_ok=True)
            data_dir.mkdir(parents=True, exist_ok=True)

        _crash_dir = cache_dir / "crash-artifacts" / f"node{node_id}"
        try:
            _crash_dir.mkdir(parents=True, exist_ok=True)
        except PermissionError:
            import subprocess as _sp_crash, os as _os_crash
            _sp_crash.run(["sudo", "mkdir", "-p", str(_crash_dir)], check=True, capture_output=True)
            _sp_crash.run(
                ["sudo", "chown", f"{_os_crash.getuid()}:{_os_crash.getgid()}", str(_crash_dir)],
                check=True, capture_output=True,
            )

        if freshly_cloned:
            # 5.x: chain MDBX copied from a live donor may be corrupt; wipe chains
            # but keep global_db (contains node list needed for balancer bootstrap)
            _stage_cfg = config_loader.load_stage_config()
            _gver = _stage_cfg.get('genesis_version', '')
            if not _gver.startswith('v6'):
                import subprocess as _sp
                for mdbx_subdir in ("lib/network",):
                    mdbx_dir = data_dir / mdbx_subdir
                    if mdbx_dir.is_dir():
                        _sp.run(["sudo", "rm", "-rf", str(mdbx_dir)], check=True, capture_output=True)
                        _sp.run(["sudo", "mkdir", "-p", str(mdbx_dir)], check=True, capture_output=True)
                        print_info(_("    mdbx_wipe: {} for {}").format(mdbx_subdir, svc_name))

        if freshly_cloned and spec.regenerate_cert:
            import glob as _glob
            ca_dir = data_dir / "lib" / "ca"
            if ca_dir.is_dir():
                for cert_file in _glob.glob(str(ca_dir / "node-addr*")):
                    Path(cert_file).unlink(missing_ok=True)
                print_info(_("    regenerate_cert: removed node-addr certs for {}").format(svc_name))

        if spec.config_overrides:
            cfg_d = cfg_dir / "cellframe-node.cfg.d"
            cfg_d.mkdir(parents=True, exist_ok=True)
            lines = [f"# Auto-generated config overrides for {svc_name}"]

            def _cfg_val(v):
                if isinstance(v, bool):
                    return "true" if v else "false"
                s = str(v)
                import re as _r
                return _r.sub(
                    r'\{\{(\w+)\}\}',
                    lambda m: str(override_vars.get(m.group(1), m.group(0))),
                    s,
                )

            override_vars = {
                'network_name': network_mgr.topology.network.name,
                **(suite_variables or {}),
            }

            for section, values in spec.config_overrides.items():
                lines.append(f"\n[{section}]")
                if isinstance(values, dict):
                    for k, v in values.items():
                        lines.append(f"{k}={_cfg_val(v)}")
                else:
                    lines.append(str(values))
            (cfg_d / "suite-overrides.cfg").write_text("\n".join(lines) + "\n")
            print_info(_("    config_overrides: {}").format(list(spec.config_overrides.keys())))

            if 'srv_vpn' in spec.config_overrides:
                srv_vpn_cfg = spec.config_overrides['srv_vpn']
                if isinstance(srv_vpn_cfg, dict) and 'wallet_addr' not in srv_vpn_cfg:
                    net_name = override_vars.get('network_name', 'vpntest')
                    fee_addr = None
                    for nid in range(1, max_existing_id + 1):
                        main_cfg_path = cache_dir / "configs" / f"node{nid}" / "network" / net_name / "main.cfg"
                        if main_cfg_path.exists():
                            import configparser
                            _p = configparser.ConfigParser()
                            _p.read(str(main_cfg_path))
                            for _sect in ('esbocs', 'dag', 'general'):
                                fee_addr = _p.get(_sect, 'fee_addr', fallback=None)
                                if fee_addr:
                                    break
                            if fee_addr:
                                break
                    if fee_addr:
                        receipt_cert = f"{net_name}.root.pvt.0"
                        billing_lines = [
                            f"# Auto-generated billing config for {svc_name}",
                            f"\n[srv_vpn]",
                            f"wallet_addr={fee_addr}",
                            f"receipt_sign_cert={receipt_cert}",
                        ]
                        (cfg_d / "vpn-billing.cfg").write_text("\n".join(billing_lines) + "\n")
                        print_info(_("    vpn-billing: wallet_addr={}... cert={}").format(fee_addr[:20], receipt_cert))

                        ca_dir = data_dir / "lib" / "ca"
                        ca_dir.mkdir(parents=True, exist_ok=True)
                        signing_cert = f"{receipt_cert}.dcert"
                        if not (ca_dir / signing_cert).exists():
                            for nid in range(1, max_existing_id + 1):
                                src_cert = cache_dir / "data" / f"node{nid}" / "lib" / "ca" / signing_cert
                                if src_cert.exists():
                                    import subprocess as _sp
                                    _sp.run(["sudo", "cp", "-a", str(src_cert), str(ca_dir / signing_cert)],
                                            check=True, capture_output=True)
                                    print_info(_("    signing cert: copied {} from node{}").format(signing_cert, nid))
                                    break

        if spec.packages:
            packages_to_install[svc_name] = spec.packages.split()

        print_info(_("  {}  id={} role={} {}:{}").format(svc_name, node_id, spec.role, ip_addr, http_port))

    if not compose_specs:
        return

    _generate_unique_node_certs(cache_dir, compose_specs, base_path,
                                print_info, print_warning)

    stage_config = config_loader.load_stage_config()
    try:
        network_mgr.compose.add_extra_node_services(
            compose_specs,
            network_settings=stage_config,
            cache_dir_relative=str(Path(config_loader.get_paths_config().get('cache_dir', '../../cache'))),
        )
    except Exception as e:
        print_error(_("  Failed to provision node_compose: {}").format(e))
        return

    svc_names = [s['service_name'] for s in compose_specs]

    # --- Prototype pattern for package installation -------------------------
    # Group services that share the same package set.  For each group with
    # more than one member we start only the prototype, install packages,
    # docker-commit it, then replicate the committed image to siblings.
    # This avoids running apt-get N times for N identical containers.
    pkg_groups: dict[tuple, list[str]] = {}
    for svc, pkgs in packages_to_install.items():
        key = tuple(sorted(pkgs))
        pkg_groups.setdefault(key, []).append(svc)

    clone_map: dict[str, list[str]] = {}
    deferred_svcs: set[str] = set()

    for _pkg_key, group_svcs in pkg_groups.items():
        if len(group_svcs) > 1:
            prototype = group_svcs[0]
            siblings = group_svcs[1:]
            clone_map[prototype] = siblings
            deferred_svcs.update(siblings)

    start_first = [s for s in svc_names if s not in deferred_svcs]
    try:
        network_mgr.compose.up(services=start_first, detach=True, wait=False, no_build=True)
        print_success(_("  Started: {}").format(', '.join(start_first)))
    except Exception as e:
        print_error(_("  Failed to start services: {}").format(e))
        return

    for svc_name, pkgs in packages_to_install.items():
        if svc_name in deferred_svcs:
            continue
        pkg_str = " ".join(pkgs)
        try:
            exit_code, output = network_mgr.compose.exec(
                svc_name, ["bash", "-c", f"apt-get update -qq && apt-get install -y -qq {pkg_str} && rm -rf /var/lib/apt/lists/*"]
            )
            if exit_code != 0:
                print_warning(_("  [{}] package install failed: {}").format(svc_name, output[:200]))
            else:
                print_info(_("  [{}] installed: {}").format(svc_name, pkg_str))
        except Exception as e:
            print_warning(_("  [{}] package install error: {}").format(svc_name, e))

    if clone_map:
        _commit_and_clone_prototypes(
            network_mgr.compose, clone_map,
            print_info, print_warning,
        )
        try:
            network_mgr.compose.up(
                services=list(deferred_svcs), detach=True,
                wait=False, no_build=True,
            )
            print_success(_("  Started from prototype image: {}").format(', '.join(sorted(deferred_svcs))))
        except Exception as e:
            print_error(_("  Failed to start cloned services: {}").format(e))


def regenerate_node_certs(cache_dir: Path, nodes: dict, base_path: Path,
                          logger_fn=None, warn_fn=None) -> dict:
    """Generate unique node-addr certs for arbitrary nodes.

    Uses ``cf-cert-generator --single`` (Docker) which outputs the node
    address deterministically.  Certs are written to ``cache/data/nodeN/lib/ca/``.

    Args:
        cache_dir: Path to cache directory.
        nodes: Dict mapping node_id (int) → service_name (str).
        base_path: Project base path for CertGenerator.
        logger_fn: Optional info callback(msg).
        warn_fn: Optional warning callback(msg).

    Returns:
        Dict mapping service_name → node address string.
    """
    from ..certs.generator import CertGenerator

    cert_gen = CertGenerator(base_path)
    addr_map: dict = {}

    for node_id, svc_name in nodes.items():
        ca_dir = cache_dir / "data" / f"node{node_id}" / "lib" / "ca"
        ca_dir.mkdir(parents=True, exist_ok=True)
        for f in ca_dir.iterdir():
            if f.name == "node-addr.dcert":
                f.unlink()

        addr = cert_gen.generate_single_node_cert(ca_dir, cert_name="node-addr")
        if addr:
            addr_map[svc_name] = addr
            if logger_fn:
                logger_fn(f"    [{svc_name}] node-addr → {addr}")
        else:
            if warn_fn:
                warn_fn(f"    [{svc_name}] failed to generate unique node-addr")

    return addr_map


def _generate_unique_node_certs(cache_dir: Path, compose_specs: list, base_path: Path,
                                print_info, print_warning) -> dict:
    """Generate unique node-addr certs for node_compose_gen nodes.

    Thin wrapper around :func:`regenerate_node_certs`.
    """
    nodes = {s['id']: s['service_name'] for s in compose_specs}
    return regenerate_node_certs(cache_dir, nodes, base_path,
                                 logger_fn=print_info, warn_fn=print_warning)


def _find_donor_node(cache_dir: Path, subdir: str) -> Optional[str]:
    """Find first existing node directory (e.g. 'node1') in cache_dir/subdir."""
    import os
    target = cache_dir / subdir
    if not target.exists():
        return None
    for d in sorted(os.listdir(target)):
        if d.startswith("node") and (target / d / "cellframe-node.cfg").exists():
            return d
    return None


def register_commands(app: typer.Typer, base_path: Path, get_config_path: Callable[[], Optional[Path]]):
    """Register test execution commands."""
    
    @app.command()
    def run_tests(
        test_dirs: List[str] = typer.Argument(..., help="Test scenario directories to run"),
        parallel: bool = typer.Option(False, "--parallel", "-p", help="Run tests in parallel (not yet implemented)"),
        filter: Optional[str] = typer.Option(None, "--filter", "-k", help="Filter tests by pattern"),
        start_network: bool = typer.Option(True, "--start-network/--no-start-network", help="Start network before tests"),
        stop_after: bool = typer.Option(True, "--stop-after/--keep-running", help="Stop network after tests"),
    ):
        """🧪 Run YAML test scenarios from specified directories."""
        
        from ..scenarios.parser import ScenarioParser
        from ..scenarios.executor import ScenarioExecutor, ScenarioExecutionError
        from ..scenarios.schema import SuiteDescriptor
        from src.utils.artifacts import ArtifactsManager
        from ..config.manager import get_config_loader
        from ..network.manager import NetworkManager
        from ..monitoring.manager import MonitoringManager
        from src.utils.report_generator import ReportGenerator
        from ..scenarios.extractors import set_debug_mode
        import docker
        from src.utils.logger import logger
        
        _dir_suffix = _("y") if len(test_dirs) == 1 else _("ies")
        print_info(_("Running tests from {} director{}:").format(len(test_dirs), _dir_suffix))
        for test_dir in test_dirs:
            print_info(_("  • {}").format(test_dir))
        
        # Load configuration
        config_loader = get_config_loader()
        artifacts_config = config_loader.get_artifacts_config()
        artifacts_manager = ArtifactsManager(base_path, artifacts_config)
        
        # Load scenarios config and set debug mode
        scenarios_config = config_loader.get_scenarios_config()
        debug_mode = scenarios_config.get('debug', False)
        set_debug_mode(debug_mode)
        
        if debug_mode:
            print_info(_("🐛 Debug mode enabled for scenario extraction"))
        
        # Create run ID - one timestamp for entire test session
        timestamp_str = datetime.now().strftime('%Y%m%d_%H%M%S')
        run_id = timestamp_str
        
        # Create base run directory
        run_dir_base = artifacts_manager.artifacts_root / f"run_{run_id}"
        run_dir_base.mkdir(parents=True, exist_ok=True)
        
        print_info(_("📁 Created run directory: run_{}/").format(run_id))
        
        # Start network if requested
        network_mgr = None
        if start_network:
            print_info(_("\n🚀 Starting test network..."))
            config_path = get_config_path()
            network_mgr = NetworkManager(base_path, topology_name="default", config_path=config_path)
            # Pass keep_running flag to prevent network shutdown on errors
            network_mgr.keep_running = not stop_after
            
            async def _start_network():
                await network_mgr.start(rebuild=False, wait_ready=True)
            
